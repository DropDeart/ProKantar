using BaseForge.API.Extensions;
using Microsoft.AspNetCore.HttpOverrides;
using Microsoft.EntityFrameworkCore;
using Microsoft.OpenApi;
using Scalar.AspNetCore;
using Platform.Data;

// h2c (TLS'siz HTTP/2) desteği — container/yerel ağda düz HTTP üzerinden gRPC istemci çağrıları için.
AppContext.SetSwitch("System.Net.Http.SocketsHttpHandler.Http2UnencryptedSupport", true);

// Yerel 'dotnet run': .env'deki secret'ları (ConnectionStrings__Default vb.) process environment'a yükler.
// NoClobber: gerçek ortam değişkenleri (docker-compose) her zaman önceliklidir; dosya yoksa no-op.
DotNetEnv.Env.NoClobber().Load();

var builder = WebApplication.CreateBuilder(args);

// Merkezi loglama: Serilog + (yapılandırılmışsa) Grafana Loki. Serilog:LokiUrl boşsa
// sadece konsola loglar — Loki'nin ayakta olması bir ön koşul değildir.
builder.AddBaseForgeLogging("platform");

// SPA'lardan (farklı origin) çağrılabilmesi için — izinli origin'ler appsettings/env'den
// gelir, kod değişikliği/regen gerekmez (bkz. appsettings.json "Cors:AllowedOrigins").
var allowedOrigins = builder.Configuration.GetSection("Cors:AllowedOrigins").Get<string[]>() ?? [];
builder.Services.AddCors(cors =>
{
    cors.AddPolicy("ConfiguredOrigins", policy =>
    {
        if (allowedOrigins.Length > 0)
        {
            policy.WithOrigins(allowedOrigins).AllowAnyHeader().AllowAnyMethod();
        }
    });
});

builder.Services.AddControllers();
builder.Services.AddGrpc(grpc => grpc.Interceptors.Add<BaseForge.API.Grpc.CorrelationIdServerInterceptor>());
builder.Services.AddOpenApi(openApi =>
{
    // Scalar'daki "Introduction" bölümü bu bilgilerden gelir (Markdown desteklenir).
    openApi.AddDocumentTransformer((document, _, _) =>
    {
        document.Info.Title = "Platform API";
        document.Info.Version = "v1";
        document.Info.Description = "# Platform API\n\nBaseForge ile üretilen **platform** mikroservisi · _platform microservice generated by BaseForge_.\n\n## 🇹🇷 Türkçe\nBu servis **platform** bounded context'ini yönetir ve şu kaynaklar için CRUD uçları sunar: **Carrier, Driver, Vehicle, Trailer, DriverVehicle, Device**. Her kaynak için oluşturma, güncelleme, silme (soft delete), tekil getirme ve listeleme uçları vardır.\n\nMimari: Clean Architecture + CQRS (MediatR). Veri erişimi: EF Core (+ karmaşık sorgular için Dapper). Veritabanı: PostgreSQL (servise özel, `prokantar_platform_db`). Başka servislere referanslar yalnızca ID iledir (cross-DB FK yoktur).\n\n## 🇬🇧 English\nThe **platform** microservice owns the **platform** bounded context and exposes CRUD endpoints for: **Carrier, Driver, Vehicle, Trailer, DriverVehicle, Device**. Each resource provides create, update, delete (soft delete), get-by-id and list endpoints.\n\nArchitecture: Clean Architecture + CQRS (MediatR). Data access: EF Core (+ Dapper for complex queries). Database: PostgreSQL (per service, `prokantar_platform_db`). References to other services are ID-only (no cross-DB foreign keys).";
        return Task.CompletedTask;
    });

    // JWT korumalı servis: OpenAPI dokümanına Bearer security scheme'i ekle
    // (Scalar'daki "Authentication" panelinin kaynağı budur).
    openApi.AddDocumentTransformer((document, _, _) =>
    {
        document.Components ??= new OpenApiComponents();
        document.Components.SecuritySchemes ??= new Dictionary<string, IOpenApiSecurityScheme>();
        document.Components.SecuritySchemes["Bearer"] = new OpenApiSecurityScheme
        {
            Type = SecuritySchemeType.Http,
            Scheme = "bearer",
            BearerFormat = "JWT",
            Description = "Identity'nin `/connect/token` ucundan aldığınız access_token'ı buraya yapıştırın.",
        };
        document.Security ??= [];
        document.Security.Add(new OpenApiSecurityRequirement
        {
            [new OpenApiSecuritySchemeReference("Bearer", document)] = [],
        });
        return Task.CompletedTask;
    });
});
builder.Services.AddBaseForge(options =>
{
    options.UsePostgreSQL<PlatformDbContext>(
        builder.Configuration.GetConnectionString("Default")
            ?? throw new InvalidOperationException("ConnectionStrings:Default tanımlı değil."));
    options.EnableCQRS(typeof(Program).Assembly);
    options.EnableAuditLog();
    options.EnableJwt(jwt =>
    {
        // Merkez Identity (discovery/JWKS). Ortama göre Auth__Authority ile ezilebilir (prod'da
        // host.docker.internal genelde geçerli değildir).
        jwt.Authority = builder.Configuration["Auth:Authority"] ?? "http://host.docker.internal:8081";
        // Identity'nin kendi Auth:Issuer'ı ile aynı olmalı. Discovery'deki issuer'a ek olarak kabul edilir;
        // Identity yeniden başlarken discovery geçici olarak boş dönse bile istekler 401'e düşmez.
        jwt.Issuer = builder.Configuration["Auth:Issuer"] ?? string.Empty;
        jwt.Audience = "baseforge-api";
        jwt.RequireHttpsMetadata = false;
        // Arka plan işlerinden yapılan gRPC çağrıları için Identity client_credentials istemcisi (secret .env'de).
        jwt.ServiceClientId = builder.Configuration["Auth:ServiceClient:ClientId"];
        jwt.ServiceClientSecret = builder.Configuration["Auth:ServiceClient:ClientSecret"];
    });
});



// Elle yazılan servis kayıtları: Custom/ altında ProgramHooks.ConfigureServices (bu dosya her üretimde ezilir).
Platform.ProgramHooks.Services(builder);

var app = builder.Build();

// Reverse proxy (nginx vb.) arkasında çalışırken gerçek şema/host'u (https, gerçek domain)
// Kestrel'e bildirir — aksi halde OpenAPI/discovery gibi üretilen mutlak URL'ler yanlış (http,
// proxy'nin iç adresi) görünür. Docker port publish NAT'i yüzünden istek, proxy'nin gerçek IP'si
// yerine değişken bir docker gateway IP'sinden gelir; bu yüzden KnownIPNetworks/KnownProxies temizlenir
// (herkesten gelen X-Forwarded-* güvenilir sayılır). Güvenlik, container portunun yalnızca
// 127.0.0.1'e (host loopback) publish edilmesinden gelir — dışarıdan bu porta doğrudan erişilemez,
// yalnızca aynı host'taki nginx erişebilir.
var forwardedHeadersOptions = new ForwardedHeadersOptions
{
    ForwardedHeaders = ForwardedHeaders.XForwardedFor | ForwardedHeaders.XForwardedProto,
};
forwardedHeadersOptions.KnownIPNetworks.Clear();
forwardedHeadersOptions.KnownProxies.Clear();
app.UseForwardedHeaders(forwardedHeadersOptions);

// Şemayı her ortamda oluştur — önceden yalnızca Development'ta yapılıyordu ve üretilen projede EF
// migration olmadığı için production'da tablolar hiç oluşmuyordu. Postgres erişilemezse uygulama yine
// de açılır. DİKKAT: EnsureCreated var olan bir veritabanını güncellemez; spec'e alan/entity eklendiğinde
// mevcut bir veritabanı için EF Core migration gerekir (bkz. docs/ARCH.md §4).
try
{
    using var scope = app.Services.CreateScope();
    scope.ServiceProvider.GetRequiredService<PlatformDbContext>().Database.EnsureCreated();
}
catch (Exception ex)
{
    app.Logger.LogWarning(ex, "Veritabanı şeması oluşturulamadı (Postgres çalışıyor mu?). API arayüzü yine de açık.");
}

if (app.Environment.IsDevelopment())
{
    // API arayüzü: /scalar/v1 (OpenAPI: /openapi/v1.json)
    app.MapOpenApi();
    app.MapScalarApiReference(options =>
    {
        options.WithTitle("Platform API");
        options.WithTheme(ScalarTheme.Default);
        // Dark mode toggle varsayılan açık. Gizlemek için: options.HideDarkModeToggle();

        // "Ask AI" (Agent Scalar): localhost'ta key'siz ücretsiz/limitli çalışır.
        // Production'da Scalar Agent key'i ver: options.WithAgentKey("SCALAR_AGENT_KEY");
        // Veya veri gizliliği için tamamen kapat:        options.DisableAgent();

        // Token'ı Identity'nin /connect/token ucundan alıp buraya bir kere yapıştırın;
        // "Persist" sayesinde sayfa yenilense de kaybolmaz (localStorage).
        options.AddHttpAuthentication("Bearer", auth => auth.WithToken(string.Empty));
        options.AddPreferredSecuritySchemes("Bearer");
        options.EnablePersistentAuthentication();
    });
}

app.UseCors("ConfiguredOrigins");
app.UseStaticFiles(); // wwwroot/uploads — MediaController'ın fiziksel olarak kaydettiği dosyalar için
app.UseBaseForge();
// Elle yazılan middleware/endpoint'ler: Custom/ altında ProgramHooks.ConfigureApp.
Platform.ProgramHooks.App(app);
app.MapControllers();
// gRPC uçları kimlik doğrulaması ister: kullanıcı token'ı (çağıran servis iletir) ya da servis token'ı
// (client_credentials). Bkz. docs/ARCH.md §5.1.1.
app.MapGrpcService<Platform.Grpc.CarrierGrpcService>().RequireAuthorization();
// Şoför kaydı yalnız servis token'ıyla (bf_svc) okunur (elle; BaseForge regen'de yeniden ekleyin).
app.MapGrpcService<Platform.Grpc.DriverGrpcService>().RequireAuthorization(policy => policy.RequireClaim("bf_svc", "1"));
app.MapGrpcService<Platform.Grpc.VehicleGrpcService>().RequireAuthorization();
app.MapGrpcService<Platform.Grpc.TrailerGrpcService>().RequireAuthorization();
app.MapGrpcService<Platform.Grpc.DriverVehicleGrpcService>().RequireAuthorization();
app.MapGrpcService<Platform.Grpc.DeviceGrpcService>().RequireAuthorization();
app.Run();
