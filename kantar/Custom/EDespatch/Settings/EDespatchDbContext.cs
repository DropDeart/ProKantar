using Microsoft.EntityFrameworkCore;

namespace Kantar.Custom.EDespatch.Settings;

/// <summary>
/// e-İrsaliye modülünün kendi küçük context'i. <c>KantarDbContext</c> üretilmiş ve <c>sealed</c> olduğundan
/// (genişletme noktası yok) modül tabloları aynı veritabanında ayrı bir context'le yönetilir; tablolar
/// <see cref="EDespatchSchema"/> ile açılışta idempotent kurulur.
/// </summary>
public sealed class EDespatchDbContext(DbContextOptions<EDespatchDbContext> options) : DbContext(options)
{
    /// <summary>Kiracı ayarları.</summary>
    public DbSet<EDespatchSetting> Settings => Set<EDespatchSetting>();

    /// <summary>DataProtection anahtarları.</summary>
    public DbSet<DataProtectionKeyRow> DataProtectionKeys => Set<DataProtectionKeyRow>();

    /// <inheritdoc />
    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        ArgumentNullException.ThrowIfNull(modelBuilder);
        modelBuilder.Entity<EDespatchSetting>(e =>
        {
            e.ToTable("EDespatchSettings");
            e.HasKey(s => s.TenantId);
            e.Property(s => s.ProviderKind).HasConversion<string>().HasMaxLength(30);
            e.Property(s => s.Environment).HasConversion<string>().HasMaxLength(10);
            e.Property(s => s.UserName).HasMaxLength(100);
            e.Property(s => s.SeriesPrefix).HasMaxLength(3);
            e.Property(s => s.SenderAlias).HasMaxLength(200);
            e.Property(s => s.UpdatedBy).HasMaxLength(100);
        });
        modelBuilder.Entity<DataProtectionKeyRow>(e => e.ToTable("DataProtectionKeys"));
    }
}

/// <summary>Modül tabloları (EnsureCreated var olan DB'ye tablo eklemediği için açılışta çalışır).</summary>
public static class EDespatchSchema
{
    /// <summary>İdempotent DDL.</summary>
    public const string Sql = """
        CREATE TABLE IF NOT EXISTS "EDespatchSettings" (
            "TenantId" uuid PRIMARY KEY,
            "ProviderKind" varchar(30) NOT NULL,
            "Environment" varchar(10) NOT NULL,
            "UserName" varchar(100) NULL,
            "ProtectedPassword" text NULL,
            "SeriesPrefix" varchar(3) NULL,
            "SenderAlias" varchar(200) NULL,
            "UpdatedAt" timestamp with time zone NOT NULL,
            "UpdatedBy" varchar(100) NULL
        );
        CREATE TABLE IF NOT EXISTS "EDespatchNumberSequences" (
            "TenantId" uuid NOT NULL,
            "Prefix" varchar(3) NOT NULL,
            "Year" integer NOT NULL,
            "LastNumber" bigint NOT NULL,
            PRIMARY KEY ("TenantId", "Prefix", "Year")
        );
        CREATE TABLE IF NOT EXISTS "EDespatchSecrets" (
            "Name" varchar(50) PRIMARY KEY,
            "ProtectedValue" text NOT NULL
        );
        CREATE TABLE IF NOT EXISTS "DataProtectionKeys" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "FriendlyName" text NULL,
            "Xml" text NOT NULL
        );
        """;
}
